"""LaTeX rows of the tables in the report (Section 4.B), generated from results/final_*.json and
results/bench_port_*.json so that no number is copied by hand.

    ~/tee-local/venv/bin/python make_report_tables.py        -> results/report_tables.tex
"""
import json
from pathlib import Path

import analyze_final as af

OUT = Path(__file__).resolve().parent / "results"

AUT = [  # (row label, method name, indent, bold columns)
    ("TEE baseline (one run)", "baseline", 0),
    ("+ MRF, $\\beta = 0.25$", "baseline + MRF 0.25", 1),
    ("10 restarts, lowest inertia", "restarts 10", 0),
    ("+ MRF, $\\beta = 0.25$", "restarts 10 + MRF 0.25", 1),
    ("+ majority filter 20\\,m", "restarts 10 + majority 20 m", 1),
    ("+ Gaussian pre-filter 10\\,m", "Gauss 10 m + restarts 10", 1),
    ("Over-cluster 32 + Ward + refine", "over32 S=300K0", 0),
    ("+ MRF, $\\beta = 0.25$ (proposed)", "over32 S=300K0 + MRF 0.25", 1),
    ("+ Gaussian pre-filter 10\\,m", "Gauss 10 m + over32 S=300K0", 1),
]
GBG = [("TEE baseline (one run)", "baseline"), ("10 restarts, lowest inertia", "restarts 10"),
       ("Over-cluster 32 + Ward + refine", "over32 S=300K0"), ("\\quad + MRF, $\\beta = 0.25$ (proposed)", "over32 S=300K0 + MRF 0.25"),
       ("\\quad + Gaussian pre-filter 10\\,m", "Gauss 10 m + over32 S=300K0")]


def bench(which, k):
    f = OUT / f"bench_port_{which}.json"
    return json.loads(f.read_text())["k"][str(k)] if f.exists() else {}


def ms(t):
    return f"{t['median'] / 1000:.2f} ({t['p25'] / 1000:.2f}--{t['p75'] / 1000:.2f})" if t else "--"


if __name__ == "__main__":
    _, A = af.summarise("aut2022")
    _, G = af.summarise("gbg")
    lines = ["% generated by experiments/spatial_hdbscan/make_report_tables.py", "% --- Table: Austrian tile"]
    for label, name, indent in AUT:
        r = A[name]
        d = "--" if name == "baseline" else f"${r['AMI_diff']:+.3f}$ [${r['AMI_lo']:+.3f}$, ${r['AMI_hi']:+.3f}$]"
        lines.append(f"{'\\quad ' * indent}{label} & ${r['AMI']:.3f} \\pm {r['AMI_sd']:.3f}$ & {d} & {r['ARI_gt']:.3f} & "
                     f"{r['stab']:.2f} [{r['stab_lo']:.2f}, {r['stab_hi']:.2f}] & {100 * r['homog']:.1f} & {100 * r['speckle']:.1f} & "
                     f"{100 * r['edge']:.1f} \\\\")
    lines.append("% --- Table: Gothenburg viewport (stability, coherence) and runtime in JavaScript")
    b5, b17, a17 = bench("gbg", 5), bench("gbg", 17), bench("aut", 17)
    for label, name in GBG:
        r = G[name]
        lines.append(f"{label} & {r['stab']:.2f} [{r['stab_lo']:.2f}, {r['stab_hi']:.2f}] & {r['stab_min']:.2f} & {100 * r['coherence']:.1f} & "
                     f"{ms(b5.get(name))} & {ms(b17.get(name))} & {ms(a17.get(name))} \\\\")
    lines.append("% --- runtime of all benchmarked methods: k = 5 Gothenburg | k = 17 Gothenburg | k = 5 Austria | k = 17 Austria (median s)")
    a5 = bench("aut", 5)
    for name in b5:
        lines.append(f"% {name:42s} {ms(b5.get(name)):>20s} | {ms(b17.get(name)):>20s} | {ms(a5.get(name)):>20s} | {ms(a17.get(name)):>20s}")
    (OUT / "report_tables.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
